# with this, the current experiment file is executable while being able to use src as a package
import sys, os
sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from src.mytools import sample
from src.cycle_shifts import DP_DFS, Domino, CST


def sorted_powers_dec (step: int, width: int, method: CST):
    """
    Ignores signs and yields the sorted sequence generated by `method`.

    Signs are ignorable because they do not contribute to cost, so the rest of the digest should be the same.
    """
    return sorted(power for _, power in method.decompose(step, width))


if __name__ == '__main__':
    max_width = 50
    max_samples = 10_000
    total_hits = total_samples = 0
    hit = lambda a, b: a == b

    with open(f'./.ignore/{os.path.basename(__file__).split(".")[0]}_digest.txt', 'w') as f:
        for n in range(1, max_width + 1):
            # compute and compare sequences between both methods for all shifts
            samples = sample(n, max_samples)
            seq_dfs = [sorted_powers_dec(jump, n, DP_DFS()) for jump in samples]
            seq_dom = [sorted_powers_dec(jump, n, Domino()) for jump in samples]
            hits = sum(1 for pub in zip(seq_dfs, seq_dom) if hit(*pub))
            misses = [(n, jump, dfs, dom) for jump, dfs, dom in zip(samples, seq_dfs, seq_dom, strict=True) if not hit(dfs, dom)]
            total_hits += hits
            total_samples += len(samples)

            if n == 1: 
                f.write('n   | Local similarity\n----|-----------------\n')
            for (n, jump, dfs, dom) in misses: 
                f.write(f'(!) ---> w: {n}, j: {jump} => DP-DFS: {dfs} != Domino: {dom}\n')
            f.write(f'{str(n).ljust(4)}| {hits * 100 / len(samples):.2f}%\n')
    
    print(f'\nGlobal similarity: {total_hits * 100 / total_samples:.2f}%\n')
    